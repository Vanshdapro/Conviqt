// One-shot generator: pulls real monthly closes from Yahoo's public chart
// endpoint and emits src/lib/edu/data/prices.ts as a bundled, reproducible
// snapshot for the academic Research Sandbox. Re-run to refresh the snapshot.
//
//   node scripts/fetch-edu-prices.mjs
//
// The Sandbox reshapes a HISTORICAL series into a counterfactual; it does not
// need live prices, so a committed snapshot is correct (and reproducible for
// citations). Provenance + asOf are written into the file header.

import { writeFileSync } from "node:fs";

const ASSETS = [
  { ticker: "AAPL", name: "Apple Inc.", note: "rate-sensitive growth (tech)" },
  { ticker: "KO", name: "The Coca-Cola Company", note: "defensive, low-beta consumer staple" },
  { ticker: "XOM", name: "Exxon Mobil Corporation", note: "inflation-sensitive (energy)" },
  { ticker: "JPM", name: "JPMorgan Chase & Co.", note: "rate-sensitive financial" },
];

const RANGE = "10y";
const INTERVAL = "1mo";

async function fetchSeries(ticker) {
  const url = `https://query1.finance.yahoo.com/v8/finance/chart/${ticker}?range=${RANGE}&interval=${INTERVAL}`;
  const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0" } });
  if (!res.ok) throw new Error(`${ticker}: HTTP ${res.status}`);
  const json = await res.json();
  const r = json.chart?.result?.[0];
  if (!r) throw new Error(`${ticker}: no result`);
  const ts = r.timestamp ?? [];
  const closes = r.indicators?.quote?.[0]?.close ?? [];
  const currency = r.meta?.currency ?? "USD";
  const points = [];
  for (let i = 0; i < ts.length; i++) {
    const c = closes[i];
    if (c == null) continue;
    const d = new Date(ts[i] * 1000);
    const month = `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, "0")}`;
    points.push({ date: month, close: Math.round(c * 100) / 100 });
  }
  // Dedupe by month (Yahoo can return the in-progress month twice), keep last.
  const byMonth = new Map();
  for (const p of points) byMonth.set(p.date, p.close);
  return { currency, points: [...byMonth.entries()].map(([date, close]) => ({ date, close })) };
}

const out = [];
for (const a of ASSETS) {
  const { currency, points } = await fetchSeries(a.ticker);
  out.push({ ...a, currency, points });
  console.log(`${a.ticker}: ${points.length} monthly points`);
}

const header = `// AUTO-GENERATED by scripts/fetch-edu-prices.mjs — do not edit by hand.
// Source: Yahoo Finance public chart endpoint (monthly closes). Snapshot is a
// bundled, reproducible historical series for the Research Sandbox — the tool
// reshapes history into a counterfactual, so live prices are not required.
// Snapshot asOf: ${new Date().toISOString().slice(0, 10)}.

export interface PricePoint { date: string; close: number } // date = "YYYY-MM"
export interface DemoAsset {
  ticker: string;
  name: string;
  note: string;
  currency: string;
  points: PricePoint[];
}

export const PRICES_AS_OF = "${new Date().toISOString().slice(0, 10)}";
export const PRICES_SOURCE = "Yahoo Finance (public chart endpoint)";

export const DEMO_ASSETS: DemoAsset[] = ${JSON.stringify(out, null, 2)};

export function getAsset(ticker: string): DemoAsset | undefined {
  return DEMO_ASSETS.find((a) => a.ticker === ticker.toUpperCase());
}
`;

writeFileSync(new URL("../src/lib/edu/data/prices.ts", import.meta.url), header);
console.log("wrote src/lib/edu/data/prices.ts");
