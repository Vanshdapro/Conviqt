// One-shot generator: pulls fundamentals from SEC EDGAR (public domain, free,
// no key) and emits src/lib/edu/data/fundamentals.ts — a bundled, reproducible
// snapshot for the Market Wedge Finder DCF. Re-run to refresh.
//
//   node scripts/fetch-edu-fundamentals.mjs
//
// One companyfacts request per ticker; we extract free cash flow history
// (operating cash flow − capex, annual 10-K) and the latest shares outstanding.
// SEC requires a descriptive User-Agent and asks for <10 req/s; we go
// sequential with a small delay.

import { writeFileSync } from "node:fs";

const UA = "Conviqt Academic (research@conviqt.com)";
const TICKERS = ["AAPL", "KO", "XOM", "JPM"];

const OCF_TAGS = ["NetCashProvidedByUsedInOperatingActivities"];
const CAPEX_TAGS = [
  "PaymentsToAcquirePropertyPlantAndEquipment",
  "PaymentsToAcquireProductiveAssets",
];
const SHARE_TAGS_DEI = ["EntityCommonStockSharesOutstanding"];
const SHARE_TAGS_GAAP = [
  "CommonStockSharesOutstanding",
  "WeightedAverageNumberOfDilutedSharesOutstanding",
];

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJSON(url) {
  const res = await fetch(url, { headers: { "User-Agent": UA, Accept: "application/json" } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

// Annual (FY 10-K) values for the first tag that exists, keyed by fiscal-year end.
function annualByTag(facts, taxonomy, tags) {
  for (const tag of tags) {
    const node = facts.facts?.[taxonomy]?.[tag];
    const usd = node?.units?.USD ?? node?.units?.shares;
    if (!usd) continue;
    const byEnd = new Map();
    for (const x of usd) {
      if (x.form === "10-K" && x.fp === "FY" && x.end) byEnd.set(x.end, x.val);
    }
    if (byEnd.size) return byEnd;
  }
  return new Map();
}

function latestVal(facts, taxonomy, tags) {
  for (const tag of tags) {
    const node = facts.facts?.[taxonomy]?.[tag];
    const arr = node?.units?.shares ?? node?.units?.USD;
    if (!arr?.length) continue;
    const sorted = [...arr].filter((x) => x.end).sort((a, b) => a.end.localeCompare(b.end));
    if (sorted.length) return sorted[sorted.length - 1].val;
  }
  return null;
}

async function buildOne(ticker, cikMap) {
  const entry = cikMap.find((c) => c.ticker === ticker);
  if (!entry) throw new Error(`${ticker}: not in CIK map`);
  const cik = entry.cik;
  const padded = String(cik).padStart(10, "0");
  const facts = await getJSON(`https://data.sec.gov/api/xbrl/companyfacts/CIK${padded}.json`);

  const ocf = annualByTag(facts, "us-gaap", OCF_TAGS);
  const capex = annualByTag(facts, "us-gaap", CAPEX_TAGS);
  const fcfHistory = [...ocf.keys()]
    .filter((end) => capex.has(end))
    .sort()
    .map((end) => ({ fy: end, fcf: ocf.get(end) - capex.get(end) }))
    .slice(-6);

  const shares =
    latestVal(facts, "dei", SHARE_TAGS_DEI) ?? latestVal(facts, "us-gaap", SHARE_TAGS_GAAP);

  return { ticker, cik, name: entry.title, sharesOutstanding: shares, fcfHistory };
}

const tickersJson = await getJSON("https://www.sec.gov/files/company_tickers.json");
const cikMap = Object.values(tickersJson).map((c) => ({
  ticker: c.ticker,
  cik: c.cik_str,
  title: c.title,
}));

const out = [];
for (const t of TICKERS) {
  const f = await buildOne(t, cikMap);
  out.push(f);
  console.log(`${t}: ${f.fcfHistory.length} FY of FCF, shares=${f.sharesOutstanding}`);
  await sleep(250);
}

const header = `// AUTO-GENERATED by scripts/fetch-edu-fundamentals.mjs — do not edit by hand.
// Source: SEC EDGAR companyfacts (public domain, US Government work). Bundled,
// reproducible fundamentals snapshot for the Market Wedge Finder DCF.
// FCF = operating cash flow − capital expenditure (annual 10-K).
// Snapshot asOf: ${new Date().toISOString().slice(0, 10)}.

export interface AnnualFcf { fy: string; fcf: number } // fy = fiscal-year end "YYYY-MM-DD", fcf in USD
export interface Fundamentals {
  ticker: string;
  cik: number;
  name: string;
  sharesOutstanding: number;
  fcfHistory: AnnualFcf[]; // chronological, last ~6 fiscal years
}

export const FUNDAMENTALS_AS_OF = "${new Date().toISOString().slice(0, 10)}";
export const FUNDAMENTALS_SOURCE = "SEC EDGAR (companyfacts, 10-K)";

export const FUNDAMENTALS: Fundamentals[] = ${JSON.stringify(out, null, 2)};

export function getFundamentals(ticker: string): Fundamentals | undefined {
  return FUNDAMENTALS.find((f) => f.ticker === ticker.toUpperCase());
}
`;

writeFileSync(new URL("../src/lib/edu/data/fundamentals.ts", import.meta.url), header);
console.log("wrote src/lib/edu/data/fundamentals.ts");
